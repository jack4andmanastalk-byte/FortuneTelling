# -*- coding: utf-8 -*-
"""中国語（簡体字）→ 日本語表記への変換（mts5.31）

**なぜ必要か**: 委譲している一部のライブラリ（divicast など）は
中国語の簡体字を返します。そのまま「計算結果（事実）」に出すと、
日本語レポートに簡体字（日本語フォントに無い字形）が混ざります。
本モジュールは**表示用の文字だけ**を日本語表記へ寄せます
（数値・ID・構造は一切変えません）。

**方針（変換のしかた）**:

1. **卦名（易の64卦）＝伝統字形**（例: 既済→既濟、未済→未濟、革→革）。
   納品画像のキャプション（`水火既濟` など `data/iching_64.json` の
   `name_ja` と同じ字形）に揃えます。
2. **術語（六神・六親・神煞など）＝日本語の通用字形**（例: 青龙→青龍、
   勾陈→勾陳、腾蛇→騰蛇、驿马→駅馬、阳刃→陽刃、权→権、应→応）。
   リポジトリ内の既存表記（`世応`・`六親`・`六神`・`陰陽`、
   `data/iztro_ja_names.json` の `権`）に揃えます。
3. **表に無い文字はそのまま**通します（未知の字形を推測で置換しない
   ＝「誤った表示より、原文のまま」が安全側）。
4. 変換は**1文字単位**（単語辞書ではない）ので、文・メモの中でも安全に効きます。

`tests/test_text_ja.py` が代表例と「変換後の文字が check_scripts の
簡体字リストに残らないこと」を検証します。
"""
from __future__ import annotations

# 簡体字 → 日本語表記（1文字単位）
#   ※ 卦名の字形は html_report の _LIUYAO_HEXAGRAM_MAP / data/iching_64.json に一致させる
ZH_TO_JA_CHARS: dict[str, str] = {
    # --- 易の64卦名（簡体字のみ） ---
    "讼": "訟", "师": "師", "谦": "謙", "蛊": "蠱", "临": "臨",
    "观": "觀", "贲": "賁", "剥": "剝", "复": "復", "无": "無", "颐": "頤",
    "过": "過", "离": "離", "损": "損",
    "渐": "漸", "归": "歸", "丰": "豐", "兑": "兌", "涣": "渙", "节": "節",
    "济": "濟", "贞": "貞", "厉": "厲", "冲": "沖",
    # --- 術語（日本語の通用字形） ---
    "龙": "龍", "马": "馬", "驿": "駅", "财": "財", "孙": "孫", "应": "応",
    "时": "時", "阳": "陽", "阴": "陰", "陈": "陳", "盖": "蓋", "灾": "災",
    "谋": "謀", "贵": "貴", "输": "輸", "编": "編", "码": "碼", "腾": "騰",
    "华": "華", "权": "権", "变": "変", "图": "図", "书": "書", "记": "記",
    "录": "録", "测": "測", "统": "統", "计": "計", "结": "結", "备": "備",
    "岁": "歳", "开": "開", "关": "関", "说": "説", "读": "読", "试": "試",
    "换": "換", "间": "間",
}

# 卦名だけに適用する表。
# これらの字形は**日本語の標準字形**（例: 恒・壮・晋・随）なので、
# 本文では書き換えず、**易の64卦名**として出るときだけ伝統字形へ寄せます
# （`data/iching_64.json` の name_ja・納品画像のキャプションと同じ字形）。
ZH_TO_JA_GUA_CHARS: dict[str, str] = {
    "随": "隨", "恒": "恆", "壮": "壯", "晋": "晉",
}


def to_ja_text(value, mode: str = "term"):
    """文字列中の簡体字を日本語表記へ置換して返す（文字列以外はそのまま）

    Args:
        value: 対象の文字列（文字列以外はそのまま返す）
        mode: "term"（既定・術語向け）/ "name"（**卦名**向け＝伝統字形も適用）
    """
    if not isinstance(value, str) or not value:
        return value
    table = ZH_TO_JA_CHARS
    if mode == "name":
        table = {**ZH_TO_JA_CHARS, **ZH_TO_JA_GUA_CHARS}
    if not any(ch in table for ch in value):
        return value
    return "".join(table.get(ch, ch) for ch in value)
